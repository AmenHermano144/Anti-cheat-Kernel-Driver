#!/usr/bin/env python3
# gen_byovd_list.py — pull the loldrivers.io dataset and emit src/byovd_blob.inc
#
# usage:
#   python tools/gen_byovd_list.py                 # fetch live, overwrite src/byovd_blob.inc
#   python tools/gen_byovd_list.py --dry-run       # fetch + summarize, do not write
#   python tools/gen_byovd_list.py --input FILE    # use a local json snapshot
#   python tools/gen_byovd_list.py --no-verify     # skip tls cert check (not recommended)
#
# the generated .inc is a C header fragment included from src/byovd_scanner.c.
# it exposes two tables:
#
#   const UCHAR g_ByovdLolSha256[][32]        // image SHA-256 fingerprints
#   const CHAR *g_ByovdLolSubstrings[]        // lowercase filename / basename substrings
#
# plus their counts. the scanner keeps its own hand-curated g_ByovdManualSubstrings[]
# and the two lists are checked in parallel on every kernel image load.

import argparse
import json
import os
import re
import sys
import urllib.request
import ssl

LOLDRIVERS_URL = "https://www.loldrivers.io/api/drivers.json"

HEADER_PREAMBLE = """\
// AUTO-GENERATED by tools/gen_byovd_list.py from loldrivers.io.
// Do not edit by hand — regenerate with:
//     python tools/gen_byovd_list.py
//
// This file is included from src/byovd_scanner.c.
"""

def fetch(url, verify=True):
    ctx = None
    if not verify:
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
    req = urllib.request.Request(url, headers={"User-Agent": "Core_ac-byovd-gen/1.0"})
    with urllib.request.urlopen(req, context=ctx, timeout=60) as fh:
        return fh.read()

def load_entries(raw):
    data = json.loads(raw)
    # loldrivers ships a flat list of driver objects; some have Category == "vulnerable driver",
    # some use "Vulnerable driver". be liberal with the tag match.
    out = []
    for entry in data:
        cat = (entry.get("Category") or "").strip().lower()
        if "vulnerable" not in cat:
            continue
        out.append(entry)
    return out

# stems we skip because they are either too generic (match legit drivers) or
# are literal Microsoft ship names that must never be flagged.
SUBSTRING_DENYLIST = {
    "driver", "x86", "x64", "amd64", "windows", "default",
    # common ms / vendor system components that occasionally land in
    # loldrivers for a specific vulnerable build — SHA-256 still catches
    # the exact bad hash, but the substring would false-positive otherwise
    "afd", "acpi", "ndis", "ntfs", "tcpip", "http", "mup", "disk",
    "rdbss", "fltmgr", "ks", "hidclass", "mouclass", "kbdclass",
    "class2", "usbd", "volmgr", "partmgr", "volsnap", "storport",
    "fastfat", "fastio", "fat", "exfat", "fs",
}

# min length for a substring to be kept. "afd" or "fs" would match far too
# many legitimate paths; 4 is the floor our manual list already honors.
SUBSTRING_MIN_LEN = 4

def _normalize_stem(name):
    """Lowercase + strip common extensions; returns None if unusable."""
    s = (name or "").strip().lower()
    if not s:
        return None
    # take basename
    s = s.rsplit("/", 1)[-1].rsplit("\\", 1)[-1]
    # strip extension
    stem = re.sub(r"\.(sys|dll|exe)$", "", s)
    if not stem:
        return None
    if stem in SUBSTRING_DENYLIST:
        return None
    if len(stem) < SUBSTRING_MIN_LEN:
        return None
    if stem.isdigit():
        return None
    # tags occasionally include messy prefixes like "_xyzzz.foo_sys_x64" — drop
    # anything that still has whitespace or shell metacharacters after the strip.
    if any(c in stem for c in " \t\"'`<>|&"):
        return None
    return stem

def extract_substrings(entry):
    """Derive lowercase basename substrings suitable for a case-insensitive contains-match."""
    out = set()
    # loldrivers 2024+ schema: Tags[] holds ".sys" filenames for the entry.
    for t in entry.get("Tags") or []:
        if isinstance(t, str):
            stem = _normalize_stem(t)
            if stem:
                out.add(stem)
    # legacy / future-proof: some entries include Filename / OriginalFilename
    # under KnownVulnerableSamples[].
    for s in entry.get("KnownVulnerableSamples") or []:
        for key in ("Filename", "OriginalFilename"):
            v = s.get(key)
            if v:
                stem = _normalize_stem(v)
                if stem:
                    out.add(stem)
    return out

def extract_sha256(entry):
    """Pull SHA-256 strings from every known-vulnerable sample inside an entry."""
    out = set()
    for s in entry.get("KnownVulnerableSamples") or []:
        for key in ("SHA256",):
            v = s.get(key)
            if not v or not isinstance(v, str):
                continue
            v = v.strip().lower()
            if re.fullmatch(r"[0-9a-f]{64}", v):
                out.add(v)
        # Authentihash is a dict in current schema
        ah = s.get("Authentihash") or {}
        if isinstance(ah, dict):
            v = (ah.get("SHA256") or "").strip().lower()
            if re.fullmatch(r"[0-9a-f]{64}", v):
                out.add(v)
    return out

def c_escape(s):
    return s.replace("\\", "\\\\").replace("\"", "\\\"")

def emit_inc(sha256_set, substring_set, out_path):
    sha256_list = sorted(sha256_set)
    substring_list = sorted(substring_set)

    lines = [HEADER_PREAMBLE]
    lines.append("")
    lines.append("// ----- SHA-256 image hashes ({} entries) -----".format(len(sha256_list)))
    if sha256_list:
        lines.append("static const UCHAR g_ByovdLolSha256[][32] = {")
        for h in sha256_list:
            bytes_c = ", ".join("0x{}".format(h[i:i+2]) for i in range(0, 64, 2))
            lines.append("    { " + bytes_c + " },")
        lines.append("};")
        lines.append("#define BYOVD_LOL_SHA256_COUNT  ({}u)".format(len(sha256_list)))
    else:
        lines.append("static const UCHAR g_ByovdLolSha256[1][32] = { { 0 } };")
        lines.append("#define BYOVD_LOL_SHA256_COUNT  (0u)")
    lines.append("")
    lines.append("// ----- lowercase name substrings ({} entries) -----".format(len(substring_list)))
    if substring_list:
        lines.append("static const CHAR *g_ByovdLolSubstrings[] = {")
        for s in substring_list:
            lines.append("    \"{}\",".format(c_escape(s)))
        lines.append("};")
        lines.append("#define BYOVD_LOL_SUBSTR_COUNT  ({}u)".format(len(substring_list)))
    else:
        lines.append("static const CHAR *g_ByovdLolSubstrings[1] = { \"\" };")
        lines.append("#define BYOVD_LOL_SUBSTR_COUNT  (0u)")
    lines.append("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", help="path to a local drivers.json (skips network)")
    ap.add_argument("--output", default=None, help="override output .inc path")
    ap.add_argument("--dry-run", action="store_true", help="do not write the .inc")
    ap.add_argument("--no-verify", action="store_true", help="disable TLS verify")
    args = ap.parse_args()

    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(script_dir)
    out_path = args.output or os.path.join(repo_root, "src", "byovd_blob.inc")

    if args.input:
        with open(args.input, "rb") as fh:
            raw = fh.read()
    else:
        print("[gen] fetching {}".format(LOLDRIVERS_URL))
        raw = fetch(LOLDRIVERS_URL, verify=not args.no_verify)

    entries = load_entries(raw)
    print("[gen] {} vulnerable-driver entries".format(len(entries)))

    sha256_set = set()
    substring_set = set()
    for e in entries:
        sha256_set.update(extract_sha256(e))
        substring_set.update(extract_substrings(e))

    print("[gen] unique SHA-256 fingerprints : {}".format(len(sha256_set)))
    print("[gen] unique name substrings      : {}".format(len(substring_set)))

    if args.dry_run:
        print("[gen] --dry-run; not writing {}".format(out_path))
        return 0

    emit_inc(sha256_set, substring_set, out_path)
    print("[gen] wrote {}".format(out_path))
    return 0

if __name__ == "__main__":
    sys.exit(main() or 0)
